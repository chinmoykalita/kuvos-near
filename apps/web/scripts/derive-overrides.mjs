// Regenerates web/core files that are mechanical edits of packages/mobile-core.
// Run after every core sync: `pnpm derive`. It fails loudly if an anchor moved.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const core = join(root, '../../packages/mobile-core/src');

// Relative core imports become package imports so the copy resolves from web/core.
function packageImports(source, file) {
  return source.replace(/from (['"])(\.\.?\/[^'"]+)\1/g, (_, quote, specifier) => {
    const target = join(dirname(file), specifier).slice(core.length + 1);
    return `from ${quote}@kuvos/mobile-core/${target}${quote}`;
  });
}

// Removes the JSX block that starts at `start` and ends at the first `end` after it.
function cut(source, start, end, label) {
  const from = source.indexOf(start);
  if (from < 0) throw new Error(`derive-overrides: anchor for ${label} not found`);
  const to = source.indexOf(end, from + start.length);
  if (to < 0) throw new Error(`derive-overrides: end of ${label} not found`);
  return source.slice(0, from) + source.slice(to + end.length);
}

// Replaces exactly one occurrence of `from` (fails if it is missing).
function swap(source, from, to, label) {
  if (!source.includes(from)) throw new Error(`derive-overrides: anchor for ${label} not found`);
  return source.replace(from, to);
}

function derive(relative, edit, { leavesUnused = false } = {}) {
  const file = join(core, relative);
  const output = join(root, 'web/core', relative);
  const source = edit(packageImports(readFileSync(file, 'utf8'), file));
  mkdirSync(dirname(output), { recursive: true });
  writeFileSync(output, `// Generated by scripts/derive-overrides.mjs from packages/mobile-core/src/${relative}. Do not edit.\n${leavesUnused ? '/* eslint-disable @typescript-eslint/no-unused-vars -- state for removed native-only parts */\n' : ''}${source}`);
  console.log(`derived web/core/${relative}`);
}

